const porN3 = new Map(SEGMENTOS.map((s) => [s.n3, s]))

// Cada variante hereda macro y código del catálogo oficial — el diccionario nunca puede apuntar a
// un segmento fuera de los 14 (un typo aquí revienta en build, no en producción).
const E = (variante: string, n3: string): DiccionarioEntry => {
  const seg = porN3.get(n3)
  if (!seg) throw new Error(`Diccionario: segmento desconocido '${n3}' para variante '${variante}'`)
  return { variante, segmentoN3: seg.n3, macroN1: seg.macroN1, codigo: seg.codigo, metodo: 'EXACTO', activa: true }
}

