// Garantiza en build/test que ninguna variante colisiona tras normalizar (dos textos distintos
// que normalizan igual serían una entrada muerta — buildIndex se queda con la primera).
export function variantesDuplicadas(): string[] {
  const vistos = new Set<string>()
  const dups: string[] = []
  for (const e of DICCIONARIO) {
    const key = normalizeText(e.variante)
    if (vistos.has(key)) dups.push(e.variante)
    vistos.add(key)
  }
  return dups
}
